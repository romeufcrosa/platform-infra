#!/usr/bin/env bash
# Render dashboards/*.json into a single ConfigMap manifest.
# Deterministic output: jq -S sorts keys, so re-running produces no diff
# unless a dashboard actually changed.
set -euo pipefail
cd "$(dirname "$0")/.."

# One ConfigMap per dashboard file, emitted as a multi-document YAML stream.
# A `for` loop, not three hand-copied blocks: three copies of the same heredoc
# is three places for the label or the namespace to drift, and a fourth
# dashboard would be added by copying rather than by dropping in a file.
out=kubernetes/platform-system/platform/dashboards-configmap.yaml
: > "$out"

for json in dashboards/*.json; do
  base=$(basename "$json" .json)          # platform-overview
  # grafana-dashboard-platform-overview: the ConfigMap name is derived, never
  # typed. The sidecar selects on the `grafana_dashboard: "1"` label, so that
  # label is load-bearing, not decoration.
  name="grafana-dashboard-${base}"

  {
    echo "---"
    cat <<EOF
# Generated by scripts/render-dashboards.sh — do not edit by hand.
# Source of truth is dashboards/*.json. Run \`make dashboards\` after any
# dashboard change and commit the result.
apiVersion: v1
kind: ConfigMap
metadata:
  name: ${name}
  namespace: monitoring
  labels:
    grafana_dashboard: "1"
  annotations:
    grafana_folder: "Platform"
data:
  ${base}.json: |-
EOF
    sed 's/^/    /' <(jq -S . "$json")
  } >> "$out"
done

echo "rendered $out from $(ls dashboards/*.json | wc -l | tr -d ' ') dashboard(s)"